import fs from 'node:fs';
import assert from 'node:assert/strict';
const codes=['en','de','fr','it','es','pl','nl','ro','hu','sk','sl'];
const english=JSON.parse(fs.readFileSync('public/guide/locales/en.json','utf8'));
const keys=[...fs.readFileSync('public/guide/index.html','utf8').matchAll(/data-i18n="([^"]+)"/g)].map(m=>m[1]);
const bundle={};
function seconds(time){return time.split(':').map(Number).reduce((value,part)=>value*60+part,0);}
function stamp(value){return new Date(Math.round(value*1000)).toISOString().slice(11,23);}
function wrap(text){
  if(text.length<=45)return text;
  const words=text.split(/\s+/);let best=1;
  for(let i=1;i<words.length;i++)if(Math.abs(words.slice(0,i).join(' ').length-text.length/2)<Math.abs(words.slice(0,best).join(' ').length-text.length/2))best=i;
  return words.slice(0,best).join(' ')+'\n'+words.slice(best).join(' ');
}
let total=0,fast=[];
for(const lang of codes){
  const d=JSON.parse(fs.readFileSync(`public/guide/locales/${lang}.json`,'utf8'));
  for(const key of keys){
    assert.ok(d.copy[key],`${lang}: missing ${key}`);
    const stack=[];
    for(const tag of d.copy[key].matchAll(/<\/?(strong|b|small|a)\b[^>]*>/g)){
      if(tag[0][1]==='/')assert.equal(stack.pop(),tag[1],`${lang}: invalid HTML in ${key}`);else stack.push(tag[1]);
    }
    assert.equal(stack.length,0,`${lang}: unclosed HTML in ${key}`);
  }
  for(const key of ['allQuestions','questionCount'])assert.ok(d.copy[key].includes('{n}'),`${lang}: missing count placeholder`);
  for(const key of ['socialPostConsent','extendedSuccess','programTermTag'])for(const name of ['@combo_ski','@Comboski'])assert.ok(d.copy[key].includes(name),`${lang}: profile lost in ${key}`);
  for(const key of ['legalNote','actionRuleRights'])assert.deepEqual([...d.copy[key].matchAll(/href=([^ >]+)/g)].map(m=>m[1]),[...english.copy[key].matchAll(/href=([^ >]+)/g)].map(m=>m[1]),`${lang}: changed link`);
  assert.equal(d.lessons.length,6);
  d.lessons.forEach((lesson,i)=>{
    assert.equal(lesson.points.length,english.lessons[i].points.length);
    lesson.points.forEach((point,j)=>assert.equal(point.image,english.lessons[i].points[j].image,`${lang}: translated CSS class`));
    lesson.questions.forEach((q,j)=>{assert.equal(q.correct,english.lessons[i].questions[j].correct);assert.equal(q.answers.length,3);assert.ok(q.question&&q.answers.every(Boolean));});
  });
  assert.deepEqual(d.lessons[0].questions[1],d.lessons[4].questions[3],`${lang}: repeated question differs`);
  assert.equal(d.subtitles.flat().length,110);
  d.subtitles.forEach((chapter,i)=>{
    const cues=chapter.map(c=>{const [start,end]=c.timing.split(' --> ').map(seconds);return {start,end,text:c.text};});
    // Merge short adjacent fragments so they can be read as a sentence.
    for(let j=0;j<cues.length-1;j++){
      const a=cues[j],b=cues[j+1],fastA=a.text.length/(a.end-a.start)>23,fastB=b.text.length/(b.end-b.start)>23;
      if((fastA||fastB||a.end-a.start<1.1||b.end-b.start<1.1)&&b.start-a.end<1.3&&b.end-a.start<=7&&a.text.length+b.text.length<116){
        a.text+=' '+b.text;a.end=b.end;cues.splice(j+1,1);j--;
      }
    }
    let previous=0;
    for(let j=0;j<cues.length;j++){
      const c=cues[j],limit=cues[j+1]?.start??c.end;
      c.end=Math.min(limit,Math.max(c.end,c.start+c.text.length/20));
      assert.ok(c.start>=previous&&c.end>c.start,`${lang}: overlapping subtitle`);previous=c.end;
      if(c.text.length/(c.end-c.start)>28)fast.push(`${lang}/${i+1}/${j+1}: ${c.text}`);
    }
    fs.writeFileSync(`public/guide/assets/videos/lesson-${i+1}.${lang}.vtt`,'WEBVTT\n\n'+cues.map((c,j)=>`${j+1}\n${stamp(c.start)} --> ${stamp(c.end)} line:-3\n${wrap(c.text)}\n`).join('\n'));
    total+=cues.length;
  });
  bundle[lang]={lessons:d.lessons,copy:d.copy};
}
// Keep a line of breathing room below two-line native captions, including Czech.
for(let i=1;i<=5;i++){
  const path=`public/guide/assets/videos/lesson-${i}.vtt`;
  const vtt=fs.readFileSync(path,'utf8').replace(/^(\d{2}:\d{2}:\d{2}\.\d{3} --> \d{2}:\d{2}:\d{2}\.\d{3})(?: line:-3)?$/gm,'$1 line:-3');
  fs.writeFileSync(path,vtt);
}
fs.writeFileSync('public/guide/locales.js','// Generated by scripts/build-locales.mjs. No translation service is used at runtime.\nwindow.COMBO_LOCALES='+JSON.stringify(bundle)+';\n');
console.log(`Validated ${codes.length+1} languages, full UI keys, answer indices, repeated question, profile names and links. Built ${codes.length*5} translated subtitle files (${total} display cues).`);
if(fast.length)console.log('Reading-speed review:\n'+fast.join('\n'));
